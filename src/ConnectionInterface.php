<?php declare(strict_types=1);

namespace STDW\Contract\Pdo;

use STDW\Contract\Pdo\Param\ParamInterface;


/**
 * The physical link to one database, built from a ConfigInterface.
 *
 * Lifecycle plus transaction control. A transaction is a property of the
 * underlying PDO connection, not of the driver, so it lives here:
 * begin()/commit()/rollback()/inTransaction() delegate straight to the
 * native handle. Sharing one Connection between Models is what makes a
 * transaction span multiple Models.
 *
 * This is the ONLY place that talks to the raw PDO handle, and it is the
 * single execution boundary: the Driver (the IR translator) compiles the
 * neutral statement and delegates execution here. Execution is reached in
 * two shapes — the neutral IR (through the Driver) and raw SQL
 * (fetch/fetchAll/execute) — and both require typed Params, so a value
 * never reaches SQL as text. The native handle itself is not exposed: raw
 * access is offered through well-defined methods, not a PDO leak.
 *
 * A failure to open/close the link or to run a transaction surfaces as
 * ConnectionExceptionInterface.
 */
interface ConnectionInterface
{
    /**
     * Opens the physical connection. Idempotent.
     * 
     * @return void 
     */
    public function connect(): void;

    /**
     * Whether the physical link is currently open.
     * 
     * @return bool 
     */
    public function isConnected(): bool;

    /**
     * Closes the physical connection.
     * 
     * @return void 
     */
    public function disconnect(): void;

    /**
     * Opens a transaction on this connection. Throws when unsupported.
     * 
     * @return void 
     */
    public function begin(): void;

    /**
     * Commits the open transaction. Throws when unsupported.
     * 
     * @return void 
     */
    public function commit(): void;

    /**
     * Rolls back the open transaction. Throws when unsupported.
     * 
     * @return void 
     */
    public function rollback(): void;

    /**
     * Whether a transaction is currently open on this connection.
     * 
     * @return bool 
     */
    public function inTransaction(): bool;

    /**
     * Runs a raw SELECT and returns the first row, or null when empty.
     *
     * The caller owns the SQL (join, WITH/recursive, window functions —
     * anything the neutral IR does not model) and therefore the dialect.
     * Values are bound, never interpolated: every entry of $params MUST be
     * a ParamInterface; a raw value is rejected. $params may be positional
     * (?, a list) or named (:name, keyed by placeholder name).
     *
     * @param array<int|string, ParamInterface> $params
     * @return null|array<int|string, mixed>
     */
    public function fetch(string $sql, array $params = []): ?array;

    /**
     * Runs a raw SELECT and returns every row.
     *
     * Same contract as fetch(): the caller owns the SQL and each value is a
     * bound ParamInterface (positional ? or named :name).
     *
     * @param array<int|string, ParamInterface> $params
     * @return array<int, array<int|string, mixed>>
     */
    public function fetchAll(string $sql, array $params = []): array;

    /**
     * Runs a raw write (INSERT/UPDATE/DELETE, DDL) and returns affected rows.
     *
     * Same contract as fetch(): the caller owns the SQL and each value is a
     * bound ParamInterface. The row count comes from the engine and may be 0
     * for statements it does not report on.
     *
     * @param array<int|string, ParamInterface> $params
     * @return int
     */
    public function execute(string $sql, array $params = []): int;

    /**
     * The key generated by the last INSERT on this connection, when one was
     * generated; null otherwise.
     *
     * Exposed so the Driver can absorb the generated-key split without
     * touching the native handle: RETURNING where supported, this otherwise.
     *
     * @return null|string
     */
    public function lastInsertId(): ?string;
}
