<?php declare(strict_types=1);

namespace STDW\Contract\Pdo\Result;


/**
 * Universal return of every Driver operation — the low-level, engine-neutral
 * outcome of a translated statement.
 *
 * The driver normalizes each engine's response here, so callers never branch
 * on dialect: a SELECT yields rows(), a write yields affected(), and an insert
 * yields the generated key through insertedId() regardless of whether the
 * engine produced it through RETURNING or the native last-insert-id. The Model
 * standardizes this into a ResultInterface.
 *
 * @phpstan-type Row array<int|string, mixed>
 * @phpstan-type Rows array<int, array<int|string, mixed>>
 */
interface RawInterface
{
    /**
     * The rows produced by the statement (SELECT, or a write with returning()).
     *
     * @return Rows
     */
    public function rows(): array;

    /**
     * The number of rows affected by a write.
     * 
     * @return int 
     */
    public function affected(): int;

    /**
     * The key generated by an insert, when one was generated; null otherwise.
     *
     * Engine-neutral: the driver fills it from RETURNING where the engine
     * supports it, or from the native last-insert-id otherwise.
     * 
     * @return null|int|string 
     */
    public function insertedId(): null|int|string;
}
